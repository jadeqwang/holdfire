import pw from '/opt/node-tools/node_modules/playwright/index.js'; const { chromium } = pw;
import { serve } from './serve.mjs';
const PORT = 8600 + Math.floor(Math.random() * 90);
const server = await serve(PORT);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await b.newPage({ viewport: { width: 1920, height: 1080 } });
page.on('pageerror', (e) => console.error('[pageerror]', e.message));
page.on('console', (m) => console.log('[page]', m.text()));
await page.goto(`http://127.0.0.1:${PORT}/index.html?w=1920&h=1080&tl=t2_plate`);
await page.evaluate(() => window.__ready);
const r = await page.evaluate(async () => {
  const { Engine } = await import('./src/engine.js');
  const S = await import('./src/scenes/t2/plate/styles.js'); const L = await import('./src/scenes/t2/plate/lib.js');
  const Ly = await import('./src/scenes/t2/plate/layer.js');
  const cv = document.createElement('canvas'); cv.width = 1920; cv.height = 1080;
  const e = new Engine(cv, 1920, 1080);
  const gl = e.renderer.getContext(); const px = new Uint8Array(4);
  const sync = () => { e.renderer.setRenderTarget(null); gl.readPixels(0, 0, 1, 1, gl.RGBA, gl.UNSIGNED_BYTE, px); };
  const tex = await L.loadTex('work/plates/TEST_vista/f_00030.jpg');
  const A = L.rt(e, 'benchA');
  const out = {};
  const time = async (name, fn) => { fn(); sync(); const t0 = performance.now(); for (let i = 0; i < 3; i++) fn(); sync(); out[name] = Math.round((performance.now() - t0) / 3); };
  await time('layer', () => Ly.drawLayer(e, A, { tex }));
  for (const s of S.STYLES) await time(s, () => S.applyStyle(e, s, A.texture, e.rtScene, { seed: 3 }));
  await time('composite', () => e.composite({}, 1));
  await time('composite_plate', () => e.composite({ tonemap: 0, bloom: 0.18, halation: 0.12 }, 1));
  const t2 = await L.loadTex('work/plates/TEST_vista/f_00040.jpg');
  await time('upload_new', () => { t2.needsUpdate = true; Ly.drawLayer(e, A, { tex: t2 }); });
  return out;
});
console.log(JSON.stringify(r));
await b.close(); server.close();
